import AppKit
import UniformTypeIdentifiers

final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    var paused = false {
        didSet { lastChange = pasteboard.changeCount }
    }
    var onContent: ((ClipboardContent) -> Void)?
    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
    }
    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }
    func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard !paused else { return }
        // Respect common password-manager/private clipboard markers.
        let ignored = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType"]
        let types = pasteboard.types ?? []
        guard !types.contains(where: { ignored.contains($0.rawValue) }) else { return }
        // Prefer full-fidelity raster formats over text or URLs, regardless of pasteboard UTI.
        let imageTypes = types.filter { UTType($0.rawValue)?.conforms(to: .image) == true }
        let preference = [UTType.png, .tiff, .jpeg, .heic, .gif]
        func rank(_ pasteboardType: NSPasteboard.PasteboardType) -> Int {
            let identifier = UTType(pasteboardType.rawValue)?.identifier
            return preference.firstIndex { $0.identifier == identifier } ?? preference.count
        }
        let ordered = imageTypes.sorted {
            let left = rank($0)
            let right = rank($1)
            return left < right
        }
        for type in ordered {
            if let data = pasteboard.data(forType: type), let image = ClipboardImage(data: data) {
                onContent?(.image(image)); return
            }
        }
        // Finder may provide only a URL list; it often has no contentType resource value.
        let legacyFiles = NSPasteboard.PasteboardType("NSFilenamesPboardType")
        let isFileCopy = types.contains(.fileURL) || types.contains(legacyFiles)
        var fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]) ?? []
        if fileURLs.isEmpty {
            for type in [NSPasteboard.PasteboardType.fileURL, legacyFiles] {
                guard let property = pasteboard.propertyList(forType: type) else { continue }
                if let value = property as? String, let url = URL(string: value), url.isFileURL {
                    fileURLs.append(url)
                } else if let paths = property as? [String] {
                    fileURLs.append(contentsOf: paths.map { URL(fileURLWithPath: $0) })
                }
            }
        }
        for url in fileURLs where url.isFileURL {
            guard let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey, .contentTypeKey]),
                  values.isRegularFile == true,
                  let size = values.fileSize, size <= ClipboardImage.maximumInputBytes else { continue }
            let fileType = values.contentType ?? UTType(filenameExtension: url.pathExtension)
            guard fileType?.conforms(to: .image) == true,
                  let data = try? Data(contentsOf: url, options: [.mappedIfSafe]),
                  let image = ClipboardImage(data: data) else { continue }
            onContent?(.image(image)); return
        }
        // A file copy should never turn into a plain text path, even if the image is unsupported.
        if isFileCopy { return }
        if let text = pasteboard.string(forType: .string) { onContent?(.text(text)) }
    }
    func discardCurrentChange() { lastChange = pasteboard.changeCount }
    @discardableResult
    func copy(_ text: String) -> Bool {
        copy(.text(text))
    }
    @discardableResult
    func copy(_ content: ClipboardContent) -> Bool {
        pasteboard.clearContents()
        let result: Bool
        switch content {
        case .text(let text): result = pasteboard.setString(text, forType: .string)
        case .image(let image):
            let item = NSPasteboardItem()
            item.setData(image.pngData, forType: .png)
            if let tiff = NSImage(data: image.pngData)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
            result = pasteboard.writeObjects([item])
        }
        lastChange = pasteboard.changeCount
        return result
    }
    deinit { timer?.invalidate() }
}
